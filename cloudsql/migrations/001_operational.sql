-- S05 operational schema. All timestamps are UTC-aware PostgreSQL TIMESTAMPTZ.
-- The migration runner executes this file in one transaction.

CREATE TABLE ingest_run (
    run_id UUID PRIMARY KEY,
    job_name TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('running', 'succeeded', 'failed')),
    started_at_utc TIMESTAMPTZ NOT NULL,
    finished_at_utc TIMESTAMPTZ,
    input_count BIGINT NOT NULL DEFAULT 0 CHECK (input_count >= 0),
    output_count BIGINT NOT NULL DEFAULT 0 CHECK (output_count >= 0),
    error_message TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (finished_at_utc IS NULL OR finished_at_utc >= started_at_utc)
);
CREATE INDEX ingest_run_job_started_idx ON ingest_run (job_name, started_at_utc DESC);

CREATE TABLE ingest_file (
    ingest_file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pollutant TEXT NOT NULL CHECK (pollutant IN (
        'ozone', 'sulfur_dioxide', 'carbon_monoxide', 'nitrogen_dioxide',
        'pm25_frm_fem', 'pm25_non_frm_fem', 'pm10', 'lead'
    )),
    year INTEGER NOT NULL CHECK (year BETWEEN 1990 AND 2100),
    file_name TEXT,
    source_url TEXT,
    listed_rows BIGINT CHECK (listed_rows >= 0),
    listed_bytes BIGINT CHECK (listed_bytes >= 0),
    catalog_last_modified DATE,
    catalog_status TEXT NOT NULL CHECK (
        catalog_status IN ('listed_nonempty', 'listed_empty', 'missing')
    ),
    download_state TEXT NOT NULL DEFAULT 'pending' CHECK (
        download_state IN ('pending', 'downloaded', 'failed', 'skipped')
    ),
    stage_state TEXT NOT NULL DEFAULT 'pending' CHECK (
        stage_state IN ('pending', 'staged', 'failed', 'skipped')
    ),
    process_state TEXT NOT NULL DEFAULT 'pending' CHECK (
        process_state IN ('pending', 'processed', 'failed', 'skipped')
    ),
    raw_uri TEXT,
    raw_generation TEXT,
    raw_md5 TEXT,
    raw_size_bytes BIGINT CHECK (raw_size_bytes >= 0),
    staged_rows BIGINT CHECK (staged_rows >= 0),
    processed_rows BIGINT CHECK (processed_rows >= 0),
    last_run_id UUID REFERENCES ingest_run (run_id),
    updated_at_utc TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (pollutant, year),
    CHECK (catalog_status = 'listed_nonempty' OR download_state <> 'downloaded'),
    CHECK (download_state <> 'downloaded' OR
        (raw_uri IS NOT NULL AND raw_generation IS NOT NULL AND raw_md5 IS NOT NULL
         AND raw_size_bytes IS NOT NULL)),
    CHECK (stage_state <> 'staged' OR staged_rows IS NOT NULL),
    CHECK (process_state <> 'processed' OR processed_rows IS NOT NULL)
);
CREATE INDEX ingest_file_download_idx ON ingest_file (download_state, year);
CREATE INDEX ingest_file_stage_idx ON ingest_file (stage_state, year);

-- Each GCS generation remains traceable after a file is reissued.
CREATE TABLE ingest_file_version (
    ingest_file_id BIGINT NOT NULL REFERENCES ingest_file (ingest_file_id),
    raw_generation TEXT NOT NULL,
    raw_uri TEXT NOT NULL,
    raw_md5 TEXT NOT NULL,
    raw_size_bytes BIGINT NOT NULL CHECK (raw_size_bytes >= 0),
    downloaded_at_utc TIMESTAMPTZ NOT NULL,
    run_id UUID REFERENCES ingest_run (run_id),
    PRIMARY KEY (ingest_file_id, raw_generation)
);

CREATE TABLE pa_sensor (
    sensor_id BIGINT PRIMARY KEY,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    is_outdoor BOOLEAN NOT NULL,
    name TEXT,
    first_seen_at_utc TIMESTAMPTZ NOT NULL,
    last_seen_at_utc TIMESTAMPTZ NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (last_seen_at_utc >= first_seen_at_utc)
);

-- S08 inserts a new interval when reported sensor metadata changes.
CREATE TABLE pa_sensor_history (
    sensor_id BIGINT NOT NULL REFERENCES pa_sensor (sensor_id),
    valid_from_utc TIMESTAMPTZ NOT NULL,
    valid_to_utc TIMESTAMPTZ,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    is_outdoor BOOLEAN NOT NULL,
    name TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (sensor_id, valid_from_utc),
    CHECK (valid_to_utc IS NULL OR valid_to_utc > valid_from_utc)
);
CREATE UNIQUE INDEX pa_sensor_one_current_idx
    ON pa_sensor_history (sensor_id) WHERE valid_to_utc IS NULL;

CREATE TABLE pa_reading (
    sensor_id BIGINT NOT NULL REFERENCES pa_sensor (sensor_id),
    report_ts_utc TIMESTAMPTZ NOT NULL,
    arrival_ts_utc TIMESTAMPTZ NOT NULL,
    pm25_cf1_a DOUBLE PRECISION,
    pm25_cf1_b DOUBLE PRECISION,
    humidity_pct DOUBLE PRECISION,
    raw_uri TEXT NOT NULL,
    source_request_id TEXT NOT NULL,
    PRIMARY KEY (sensor_id, report_ts_utc)
);
CREATE INDEX pa_reading_arrival_idx ON pa_reading (arrival_ts_utc, sensor_id);

CREATE TABLE pa_poll_log (
    poll_id UUID PRIMARY KEY,
    run_id UUID REFERENCES ingest_run (run_id),
    requested_at_utc TIMESTAMPTZ NOT NULL,
    completed_at_utc TIMESTAMPTZ,
    outcome TEXT NOT NULL CHECK (
        outcome IN ('success', 'http_error', 'timeout', 'invalid_response', 'other_error')
    ),
    http_status INTEGER,
    latency_ms INTEGER CHECK (latency_ms >= 0),
    sensors_seen INTEGER NOT NULL DEFAULT 0 CHECK (sensors_seen >= 0),
    rows_inserted INTEGER NOT NULL DEFAULT 0 CHECK (rows_inserted >= 0),
    duplicate_reports INTEGER NOT NULL DEFAULT 0 CHECK (duplicate_reports >= 0),
    late_reports INTEGER NOT NULL DEFAULT 0 CHECK (late_reports >= 0),
    stale_reports INTEGER NOT NULL DEFAULT 0 CHECK (stale_reports >= 0),
    raw_uri TEXT,
    error_message TEXT,
    CHECK (completed_at_utc IS NULL OR completed_at_utc >= requested_at_utc)
);
CREATE INDEX pa_poll_log_requested_idx ON pa_poll_log (requested_at_utc DESC);

CREATE TABLE airnow_obs (
    airnow_site_id TEXT NOT NULL,
    pollutant TEXT NOT NULL CHECK (
        pollutant IN ('PM25', 'OZONE', 'NO2', 'CO', 'SO2', 'PM10')
    ),
    observed_at_utc TIMESTAMPTZ NOT NULL,
    site_name TEXT,
    concentration DOUBLE PRECISION,
    concentration_unit TEXT,
    aqi SMALLINT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    site_status TEXT,
    data_source TEXT,
    retrieved_at_utc TIMESTAMPTZ NOT NULL,
    raw_uri TEXT NOT NULL,
    source_generation TEXT NOT NULL,
    is_preliminary BOOLEAN NOT NULL DEFAULT TRUE CHECK (is_preliminary),
    PRIMARY KEY (airnow_site_id, pollutant, observed_at_utc)
);
CREATE INDEX airnow_obs_retrieved_idx ON airnow_obs
    (retrieved_at_utc, airnow_site_id, pollutant, observed_at_utc);

-- Old values are saved automatically when an observation's value or AQI changes.
CREATE TABLE airnow_obs_revision (
    revision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airnow_site_id TEXT NOT NULL,
    pollutant TEXT NOT NULL,
    observed_at_utc TIMESTAMPTZ NOT NULL,
    concentration DOUBLE PRECISION,
    concentration_unit TEXT,
    aqi SMALLINT,
    retrieved_at_utc TIMESTAMPTZ NOT NULL,
    raw_uri TEXT NOT NULL,
    source_generation TEXT NOT NULL,
    superseded_at_utc TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (airnow_site_id, pollutant, observed_at_utc)
        REFERENCES airnow_obs (airnow_site_id, pollutant, observed_at_utc)
);
CREATE INDEX airnow_revision_key_idx ON airnow_obs_revision
    (airnow_site_id, pollutant, observed_at_utc, revision_id);

CREATE FUNCTION archive_airnow_revision() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(OLD.concentration, OLD.concentration_unit, OLD.aqi)
       IS DISTINCT FROM ROW(NEW.concentration, NEW.concentration_unit, NEW.aqi) THEN
        INSERT INTO airnow_obs_revision (
            airnow_site_id, pollutant, observed_at_utc, concentration,
            concentration_unit, aqi, retrieved_at_utc, raw_uri,
            source_generation, superseded_at_utc
        ) VALUES (
            OLD.airnow_site_id, OLD.pollutant, OLD.observed_at_utc,
            OLD.concentration, OLD.concentration_unit, OLD.aqi,
            OLD.retrieved_at_utc, OLD.raw_uri, OLD.source_generation,
            NEW.retrieved_at_utc
        );
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER airnow_revision_on_change
    BEFORE UPDATE ON airnow_obs
    FOR EACH ROW EXECUTE FUNCTION archive_airnow_revision();

CREATE TABLE aqs_site (
    site_key TEXT PRIMARY KEY,
    state_code TEXT NOT NULL CHECK (state_code ~ '^[0-9]{2}$'),
    county_code TEXT NOT NULL CHECK (county_code ~ '^[0-9]{3}$'),
    site_num TEXT NOT NULL CHECK (site_num ~ '^[0-9]{4}$'),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    datum TEXT,
    site_name TEXT,
    city_name TEXT,
    county_name TEXT,
    state_name TEXT,
    first_year INTEGER,
    last_year INTEGER,
    source_uri TEXT NOT NULL,
    source_generation TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (site_key = state_code || '-' || county_code || '-' || site_num),
    CHECK (first_year IS NULL OR last_year IS NULL OR first_year <= last_year)
);
CREATE INDEX aqs_site_state_county_idx ON aqs_site (state_code, county_code);

CREATE TABLE aqs_monitor (
    monitor_key TEXT PRIMARY KEY,
    site_key TEXT NOT NULL REFERENCES aqs_site (site_key),
    parameter_code TEXT NOT NULL CHECK (parameter_code ~ '^[0-9]{5}$'),
    poc TEXT NOT NULL CHECK (poc ~ '^[0-9]{2}$'),
    method_code TEXT,
    method_name TEXT,
    begin_date DATE,
    end_date DATE,
    pm25_advisory_superseded BOOLEAN NOT NULL DEFAULT FALSE,
    source_uri TEXT NOT NULL,
    source_generation TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (site_key, parameter_code, poc),
    CHECK (monitor_key = site_key || '-' || parameter_code || '-' || poc),
    CHECK (begin_date IS NULL OR end_date IS NULL OR begin_date <= end_date)
);
CREATE INDEX aqs_monitor_parameter_idx ON aqs_monitor (parameter_code, site_key);
