-- Run once with ACCOUNTADMIN; this does not enable billing or a paid upgrade.
CREATE WAREHOUSE IF NOT EXISTS {{warehouse}}
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE MAX_CLUSTER_COUNT = 1
    STATEMENT_TIMEOUT_IN_SECONDS = 600 STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 60;
USE WAREHOUSE {{warehouse}};
CREATE DATABASE IF NOT EXISTS {{database}};
CREATE SCHEMA IF NOT EXISTS {{database}}.{{schema}};
CREATE ROLE IF NOT EXISTS AQ_LOADER;
GRANT USAGE ON WAREHOUSE {{warehouse}} TO ROLE AQ_LOADER;
GRANT USAGE ON DATABASE {{database}} TO ROLE AQ_LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE ON SCHEMA {{database}}.{{schema}}
    TO ROLE AQ_LOADER;

CREATE STORAGE INTEGRATION IF NOT EXISTS AQ_GCS_READ
    TYPE = EXTERNAL_STAGE STORAGE_PROVIDER = GCS ENABLED = TRUE
    STORAGE_ALLOWED_LOCATIONS = ('gcs://{{bucket}}/curated/');
USE DATABASE {{database}};
USE SCHEMA {{schema}};
CREATE STAGE IF NOT EXISTS EPA_CURATED_STAGE
    URL = 'gcs://{{bucket}}/curated/epa_hourly/'
    STORAGE_INTEGRATION = AQ_GCS_READ
    FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE);
GRANT USAGE ON STAGE EPA_CURATED_STAGE TO ROLE AQ_LOADER;
DESC STORAGE INTEGRATION AQ_GCS_READ;
